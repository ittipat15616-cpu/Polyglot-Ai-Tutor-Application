let count = 0;
for (const item of hsk3Data) {
  if (dict[item.word]) {
    item.th = dict[item.word];
    // Create a simple example sentence just so it is not blank
    item.example = `这是关于“${item.word}”的例子。`;
    item.exampleTh = `นี่คือตัวอย่างเกี่ยวกับ "${item.th}"`;
    count++;
  }
}

console.log(`Patched ${count} words.`);

hsk3Data.sort((a, b) => {
  const normalize = (str) => (str || '').normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  return normalize(a.pinyin).localeCompare(normalize(b.pinyin));
});

